#!/usr/bin/env bash
# Regenerate Hosven/DesignSystem/DesignTokens.swift from the design package.
#
# Source: design/hostess/tokens.json (the Hostess design system, Claude-desktop edition).
# Output: namespace DS with Colors, Spacing, Radius, Size, Opacity, Text and Shadow.
# Text styles map the package families onto system faces: display → serif,
# sans → default, mono → monospaced. CSS shadow blur maps to SwiftUI radius as blur / 2.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC="design/hostess/tokens.json"
DST="Hosven/DesignSystem/DesignTokens.swift"
python3 - "$SRC" "$DST" <<'PY'
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
tokens = json.load(open(src))

def camel(name):
    parts = name.split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

def note(usage):
    return re.sub(r"`([^`]*)`", r"\1", usage).replace("\n", " ")

def px(value):
    return value[:-2] if value.endswith("px") else value

# Colours: resolve {ref} aliases, then split #rrggbb / #rrggbbaa into hex + alpha.
raw = {t["name"]: t for t in tokens["color"]["tokens"]}
def resolve(name, theme):
    value = raw[name]["value"][theme]
    while value.startswith("{"):
        value = raw[value[1:-1]]["value"][theme]
    return value
def swift_color(value):
    hex_part = value.lstrip("#")
    rgb, alpha = hex_part[:6], hex_part[6:8]
    a = int(alpha, 16) / 255 if alpha else 1.0
    return f"Color(hex: 0x{rgb}, alpha: {a:.3f})"

weights = {300: ".light", 400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold"}
designs = {"display": ".serif", "sans": ".default", "mono": ".monospaced"}

def shadow_layers(css):
    layers = []
    for layer in re.findall(r"(-?\d+)(?:px)? (-?\d+)(?:px)? (-?\d+)(?:px)? rgba\((\d+),(\d+),(\d+),([\d.]+)\)", css):
        _, y, blur, r, g, b, a = layer
        layers.append((int(y), int(blur) / 2, int(r), int(g), int(b), float(a)))
    return layers

out = []
w = out.append
w(f"// DesignTokens.swift — generated by scripts/gen-design-tokens.sh from {src}. Do not edit by hand.")
w("import SwiftUI")
w("")
w("extension Color {")
w("    /// Hex + alpha helper for the generated palette.")
w("    init(hex: UInt32, alpha: Double = 1) {")
w("        self.init(.sRGB, red: Double((hex >> 16) & 0xff) / 255, green: Double((hex >> 8) & 0xff) / 255, blue: Double(hex & 0xff) / 255, opacity: alpha)")
w("    }")
w("    static func dynamic(light: Color, dark: Color) -> Color {")
w("        Color(NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? NSColor(dark) : NSColor(light) })")
w("    }")
w("}")
w("")
w("enum DS {")
w("    enum Colors {")
for t in tokens["color"]["tokens"]:
    w(f"        /// {note(t['usage'])}")
    w(f"        static let {camel(t['name'])} = Color.dynamic(light: {swift_color(resolve(t['name'], 'light'))}, dark: {swift_color(resolve(t['name'], 'dark'))})")
w("    }")
w("    enum Spacing {")
for t in tokens["spacing"]["tokens"]:
    w(f"        static let {camel(t['name'])}: CGFloat = {px(t['value'])}")
w("    }")
w("    enum Radius {")
for t in tokens["radius"]["tokens"]:
    w(f"        /// {note(t['usage'])}")
    w(f"        static let {t['name'].split('-', 1)[1]}: CGFloat = {px(t['value'])}")
w("    }")
w("    enum Size {")
for t in tokens["size"]["tokens"]:
    w(f"        /// {note(t['usage'])}")
    w(f"        static let {camel(t['name'])}: CGFloat = {px(t['value'])}")
w("    }")
w("    enum Opacity {")
for t in tokens["opacity"]["tokens"]:
    w(f"        static let {camel(t['name'].split('-', 1)[1])}: Double = {t['value']}")
w("    }")
w("    enum Text {")
for group in tokens["type"]["groups"]:
    design = designs[group["family"]]
    for s in group["styles"]:
        w(f"        /// {note(s['usage'])} ({s['fontSize']}/{s['lineHeight']})")
        w(f"        static let {camel(s['name'])} = Font.system(size: {px(s['fontSize'])}, weight: {weights[s['fontWeight']]}, design: {design})")
w("    }")
w("    /// A stack of drop shadows; CSS blur maps to SwiftUI radius as blur / 2.")
w("    struct Shadow {")
w("        struct Layer {")
w("            let color: Color")
w("            let radius: CGFloat")
w("            let y: CGFloat")
w("        }")
w("        let layers: [Layer]")
for t in tokens["shadow"]["tokens"]:
    light, dark = shadow_layers(t["value"]["light"]), shadow_layers(t["value"]["dark"])
    w(f"        /// {note(t['usage'])}")
    w(f"        static let {t['name'].split('-', 1)[1]} = Shadow(layers: [")
    for (ly, lr, lR, lG, lB, la), (dy, dr, dR, dG, dB, da) in zip(light, dark):
        w(f"            Layer(color: .dynamic(light: Color(hex: 0x{lR:02x}{lG:02x}{lB:02x}, alpha: {la:.2f}), dark: Color(hex: 0x{dR:02x}{dG:02x}{dB:02x}, alpha: {da:.2f})), radius: {lr:g}, y: {ly}),")
    w("        ])")
w("    }")
w("}")
open(dst, "w").write("\n".join(out) + "\n")
print(f"wrote {dst}")
PY
